"""
By Shuheque, 2026

Compute or check the HP feature-byte checksum.

The checksum is two characters after a dot, for example ".Hg".
Spaces in the feature string are ignored. The dot and the two
checksum characters are not part of the CRC input.

Each character updates an 8-bit value with HP's lookup table:
crc = table[crc XOR ascii(character)], starting from 0.
The forward pass supplies the first checksum character. The same
update over the reversed characters supplies the second. Each
result is reduced modulo 31 and indexed into HP's checksum alphabet.
"""

