if len(TABLE) != 256:
    raise RuntimeError(f"CRC table must have 256 entries, found {len(TABLE)}")


def crc8(data: bytes) -> int:
    crc = 0
    for byte in data:
        crc = TABLE[crc ^ byte]
    return crc


def feature_crc(payload: str) -> str:
    raw = payload.encode("ascii")
    forward = crc8(raw)
    reverse = crc8(raw[::-1])
    return ALPHABET[forward % 31] + ALPHABET[reverse % 31]


def split_feature_byte(text: str) -> tuple[str, str | None]:
    compact = "".join(text.split())
    if not compact:
        raise ValueError("feature byte is empty")
    if "." not in compact:
        return compact, None
    payload, _, suffix = compact.partition(".")
    if not payload:
        raise ValueError("feature byte has no characters before the checksum")
    if len(suffix) != 2:
        raise ValueError("checksum after '.' must be exactly 2 characters")
    return payload, suffix


def report(text: str) -> int:
    payload, given = split_feature_byte(text)
    computed = feature_crc(payload)
    print(f"Payload:  {payload}")
    print(f"CRC:      .{computed}")
    print(f"Full:     {payload}.{computed}")
    if given is None:
        return 0
    if given == computed:
        print(f"Check:    valid (.{given})")
        return 0
    print(f"Check:    invalid (entered .{given}, computed .{computed})")
    return 1


def main(argv: list[str]) -> int:
    if len(argv) > 1:
        text = " ".join(argv[1:])
    else:
        text = input("Feature byte: ")
    try:
        return report(text)
    except UnicodeEncodeError:
        print("Feature byte must be ASCII.", file=sys.stderr)
        return 2
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 2


if __name__ == "__main__":
    while True:
        main(sys.argv)
