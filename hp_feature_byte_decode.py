def pairs(payload: str) -> list[str]:
    if len(payload) % 2:
        raise ValueError("feature byte must contain an even number of characters")
    return [payload[i : i + 2] for i in range(0, len(payload), 2)]


def meaning(code: str) -> tuple[str, str]:
    token, description = FEATURES.get(code, ('', ''))
    if not token:
        return "?", "unknown code"
    if description:
        return token, description
    return token, "no description in the factory table"


def report(text: str) -> int:
    payload, given = crc.split_feature_byte(text)
    computed = crc.feature_crc(payload)
    codes = pairs(payload)
    print(f"Payload:    {payload}")
    if given is None:
        print(f"Checksum:   .{computed}")
        status = 0
    elif given == computed:
        print(f"Checksum:   .{computed}  valid")
        status = 0
    else:
        print(f"Checksum:   .{computed}  invalid (entered .{given})")
        status = 1
    print(f"Features:   {len(codes)}")
    print()
    width = max(len(meaning(code)[0]) for code in codes)
    for code in codes:
        token, description = meaning(code)
        print(f"{code}  {token:<{width}}  {description}")
    return status


def main(argv: list[str]) -> int:
    if len(argv) > 1:
        text = " ".join(argv[1:])
    else:
        text = input("Feature byte: ").strip()
        if not text:
            return 0
    try:
        return report(text)
    except UnicodeEncodeError:
        print("Feature byte must be ASCII.", file=sys.stderr)
        return 2
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 2


